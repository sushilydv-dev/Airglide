"""Regenerate views/font.css: the UI font embedded as a data: URI.

Windows' WebView2 (Chromium) refuses to load @font-face files from local
file:// pages (CORS), so the font is inlined instead of referenced by path.
Run after changing views/fonts/PlusJakartaSans.ttf:  python scripts/embed_font.py
"""
import base64
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
font = os.path.join(ROOT, "views", "fonts", "PlusJakartaSans.ttf")
with open(font, "rb") as f:
    data = base64.b64encode(f.read()).decode("ascii")
css = ("/* Generated by scripts/embed_font.py: Plus Jakarta Sans (SIL OFL 1.1, see fonts/OFL.txt). */\n"
       "@font-face {\n"
       '    font-family: "Plus Jakarta Sans";\n'
       f'    src: url("data:font/ttf;base64,{data}") format("truetype");\n'
       "    font-weight: 200 800;\n"
       "    font-display: swap;\n"
       "}\n")
with open(os.path.join(ROOT, "views", "font.css"), "w", encoding="utf-8") as f:
    f.write(css)
print(f"wrote views/font.css ({len(css) // 1024} KB)")
